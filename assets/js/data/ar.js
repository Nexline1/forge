  merge(FORGE.TRAITS, AR.traits, ["label", "desc"]);
  merge(FORGE.GUARDRAILS, AR.guards, ["label", "desc"]);
  merge(FORGE.TOOLACCESS, AR.access, ["label", "desc"]);
  merge(FORGE.PLANS, AR.plans, ["label", "desc", "note"]);
  merge(FORGE.CLAUDE_MODELS, AR.models, ["label", "desc", "note"]);


  function merge(list, table, fields) {
    (list || []).forEach(function (item) {
      var tr = table[item.id];
      if (!tr) return;
      fields.forEach(function (f) {
        if (tr[f] !== undefined) item[f + "_ar"] = tr[f];
      });
    });
  }

